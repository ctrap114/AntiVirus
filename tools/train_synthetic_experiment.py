#!/usr/bin/env python3
"""Measure whether inert synthetic samples improve EverbloomSecurity's AI detector.

The experiment trains two identical classifiers on the 12-dimensional runtime
feature representation:

* ``baseline`` sees only ``benign_like`` and ``packed_like`` samples;
* ``augmented`` additionally sees every other synthetic family.

Both models are evaluated on the same held-out split that contains *all*
families, including families the baseline never observed. The corpus is
generated by :mod:`everbloom_core.synthetic` and is fully inert: entry points
are a single ``RET``, no real payload exists, and every file carries the
``EVERBLOOM-SYNTHETIC-CORPUS-NOT-MALWARE`` marker.

Outputs (all under ``artifacts/`` by default):

* ``artifacts/ml-corpus/synthetic/`` — generated files + manifest;
* ``artifacts/models/synthetic_experiment/everbloom_synthetic.onnx`` — best
  model exported with the Rust-compatible ``[batch, 1, feature_dim]`` layout;
* ``artifacts/quality-baseline/synthetic_experiment.json`` — metrics report.
"""

from __future__ import annotations

import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

import numpy as np

from everbloom_core.adversarial import binary_metrics
from everbloom_core.synthetic import FAMILY_BUILDERS, generate_corpus, load_corpus_features

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_COUNTS = {
    "benign_like": 320,
    "packed_like": 220,
    "api_heavy_like": 180,
    "stealth_like": 180,
}
BASELINE_FAMILIES = ("benign_like", "packed_like")


def stratified_family_split(
    families: list[str],
    labels: np.ndarray,
    validation_fraction: float,
    test_fraction: float,
    seed: int,
) -> tuple[dict[str, np.ndarray], dict[str, np.ndarray], dict[str, np.ndarray]]:
    """Return index arrays per family for train/validation/test splits."""

    rng = np.random.default_rng(seed)
    train: dict[str, list[int]] = defaultdict(list)
    validation: dict[str, list[int]] = defaultdict(list)
    test: dict[str, list[int]] = defaultdict(list)
    for label in (0.0, 1.0):
        for family in sorted(set(families)):
            candidates = np.flatnonzero(
                np.asarray([f == family for f in families]) & (labels == label)
            )
            rng.shuffle(candidates)
            total = len(candidates)
            if total == 0:
                # Families carry a single label by construction.
                continue
            if total < 4:
                raise ValueError(
                    f"family {family!r} label {label:.0f} has too few samples ({total})"
                )
            test_count = max(1, int(round(total * test_fraction)))
            valid_count = max(1, int(round(total * validation_fraction)))
            test[family].extend(candidates[:test_count].tolist())
            validation[family].extend(candidates[test_count : test_count + valid_count].tolist())
            train[family].extend(candidates[test_count + valid_count :].tolist())
    convert = lambda part: {k: np.asarray(v, dtype=np.int64) for k, v in part.items()}  # noqa: E731
    return convert(train), convert(validation), convert(test)


def stack_indices(indices: dict[str, np.ndarray], families: tuple[str, ...] | None = None) -> np.ndarray:
    selected = [indices[f] for f in (families or indices.keys()) if f in indices and len(indices[f])]
    return np.concatenate(selected) if selected else np.zeros(0, dtype=np.int64)


def build_mlp(feature_dim: int, hidden_dim: int):
    import torch.nn as nn

    class _Model(nn.Module):
        def __init__(self) -> None:
            super().__init__()
            self.network = nn.Sequential(
                nn.Linear(feature_dim, hidden_dim),
                nn.ReLU(),
                nn.Dropout(p=0.1),
                nn.Linear(hidden_dim, hidden_dim // 2),
                nn.ReLU(),
                nn.Linear(hidden_dim // 2, 1),
            )

        def forward(self, features):
            return self.network(features.reshape(features.shape[0], -1)).squeeze(-1)

    return _Model()


def fit_model(model, features: np.ndarray, labels: np.ndarray, epochs: int, batch_size: int, learning_rate: float, seed: int):
    import torch
    import torch.nn.functional as functional

    torch.manual_seed(seed)
    optimizer = torch.optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=1e-4)
    tensor_features = torch.from_numpy(features)
    tensor_labels = torch.from_numpy(labels)
    positive = max(1.0, float((labels == 1).sum()))
    negative = max(1.0, float((labels == 0).sum()))
    pos_weight = torch.tensor([negative / positive], dtype=torch.float32)

    model.train()
    for _ in range(epochs):
        order = torch.randperm(tensor_features.shape[0])
        for start in range(0, tensor_features.shape[0], batch_size):
            batch = order[start : start + batch_size]
            logits = model(tensor_features[batch]).reshape(-1)
            loss = functional.binary_cross_entropy_with_logits(
                logits, tensor_labels[batch], pos_weight=pos_weight
            )
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=5.0)
            optimizer.step()
    model.eval()
    return model


def score(model, features: np.ndarray) -> np.ndarray:
    import torch

    with torch.no_grad():
        logits = model(torch.from_numpy(features)).detach().cpu().numpy()
    return 1.0 / (1.0 + np.exp(-np.clip(logits, -60.0, 60.0)))


def export_onnx(model, output: Path, feature_dim: int) -> None:
    import torch

    output.parent.mkdir(parents=True, exist_ok=True)
    dummy = torch.zeros(1, 1, feature_dim, dtype=torch.float32)
    torch.onnx.export(
        model,
        dummy,
        str(output),
        opset_version=17,
        input_names=["input"],
        output_names=["logit"],
        dynamic_axes={"input": {0: "batch"}, "logit": {0: "batch"}},
        dynamo=False,
        do_constant_folding=True,
    )
    contract = {
        "output_kind": "logit",
        "input_layout": ["batch", 1, feature_dim],
        "feature_dim": feature_dim,
        "synthetic_corpus_training": True,
    }
    output.with_name("model_contract.json").write_text(
        json.dumps(contract, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus-dir", type=Path, default=ROOT / "artifacts" / "ml-corpus" / "synthetic")
    parser.add_argument("--counts", type=str, default=None, help="JSON dict of family->count; defaults reproduce the standard experiment.")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--hidden-dim", type=int, default=64)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--validation-fraction", type=float, default=0.15)
    parser.add_argument("--test-fraction", type=float, default=0.2)
    parser.add_argument("--threshold", type=float, default=0.5)
    parser.add_argument("--force", action="store_true", help="Regenerate the corpus even if the sample directory is non-empty.")
    parser.add_argument("--skip-generation", action="store_true", help="Reuse an existing manifest without regenerating.")
    parser.add_argument(
        "--out-model",
        type=Path,
        default=ROOT / "artifacts" / "models" / "synthetic_experiment" / "everbloom_synthetic.onnx",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=ROOT / "artifacts" / "quality-baseline" / "synthetic_experiment.json",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()

    counts = DEFAULT_COUNTS
    if args.counts:
        counts = json.loads(args.counts)
        unknown = set(counts) - set(FAMILY_BUILDERS)
        if unknown:
            raise SystemExit(f"unknown families: {sorted(unknown)}")

    manifest = args.corpus_dir / "manifest.jsonl"
    if args.skip_generation and not manifest.exists():
        raise SystemExit(f"--skip-generation set but {manifest} does not exist")
    if not args.skip_generation:
        summary = generate_corpus(args.corpus_dir, counts, seed=args.seed, force=args.force)
        print(f"generated {summary['sample_count']} inert samples under {args.corpus_dir}")

    features, labels, families, _paths = load_corpus_features(manifest)
    if features.shape[0] == 0:
        raise SystemExit("empty corpus manifest")

    train_idx, valid_idx, test_idx = stratified_family_split(
        families, labels, args.validation_fraction, args.test_fraction, args.seed
    )

    all_train = stack_indices(train_idx)
    baseline_train = stack_indices(train_idx, BASELINE_FAMILIES)
    validation = stack_indices(valid_idx)
    test = stack_indices(test_idx)

    # Validation is used only to sanity-check convergence of both models.
    del validation

    results: dict[str, object] = {}
    for name, indices in (("baseline", baseline_train), ("augmented", all_train)):
        if indices.size == 0:
            raise SystemExit(f"{name} split is empty")
        model = build_mlp(features.shape[1], args.hidden_dim)
        fit_model(
            model,
            features[indices],
            labels[indices],
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
            seed=args.seed,
        )
        scores = score(model, features[test])
        overall = binary_metrics(scores, labels[test])
        per_family = {}
        for family in sorted(set(families)):
            mask = np.asarray([families[i] == family for i in range(len(families))])[test]
            if mask.sum():
                per_family[family] = binary_metrics(scores[mask], labels[test][mask])
        detection_scores = np.where(labels[test] == 1, scores, 1.0 - scores)
        results[name] = {
            "train_samples": int(indices.size),
            "overall": overall,
            "per_family_recall": {
                family: metrics.get("recall", metrics.get("tpr"))
                for family, metrics in per_family.items()
            },
            "per_family_fpr": {
                family: metrics.get("false_positive_rate")
                for family, metrics in per_family.items()
            },
            "mean_detection_confidence": float(detection_scores.mean()),
        }
        print(
            f"{name:9s} acc={overall['accuracy']:.3f} recall={overall['recall']:.3f} "
            f"fpr={overall['false_positive_rate']:.3f} fnr={overall['false_negative_rate']:.3f}"
        )
        if name == "augmented":
            best_model = model

    augmented_gain = (
        results["augmented"]["overall"]["recall"] - results["baseline"]["overall"]["recall"]
    )
    print(f"unseen-family recall gain from augmentation: {augmented_gain:+.3f}")

    export_onnx(best_model, args.out_model, features.shape[1])
    report = {
        "experiment": "synthetic_inert_corpus",
        "safety": {
            "entry_stub": "single RET (0xC3)",
            "marker": "EVERBLOOM-SYNTHETIC-CORPUS-NOT-MALWARE",
            "functional_payload": False,
        },
        "corpus_dir": str(args.corpus_dir),
        "counts_requested": counts,
        "feature_dim": int(features.shape[1]),
        "threshold": args.threshold,
        "seed": args.seed,
        "results": results,
        "recall_gain_from_augmentation": float(augmented_gain),
        "model_path": str(args.out_model),
        "caveat": "Synthetic corpora measure representational coverage only; "
        "production claims require authorized real-world malware and benign sets.",
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"report written to {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
