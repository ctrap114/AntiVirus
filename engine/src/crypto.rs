//! EverbloomSecurity custom stream cipher (research-grade, custom primitive).
//!
//! Design rationale: the user explicitly requested a self-designed
//! cryptographic algorithm (rather than wrapping AES/ChaCha20). The
//! algorithm here is a simple Feistel-based stream cipher with custom
//! ARX round functions and a custom S-box permutation. It is intended
//! for encryption of telemetry NDJSON payloads, quarantine metadata,
//! allowlist persistence, and analysis reports — all contexts where
//! the data is produced and consumed exclusively by the EverbloomSecurity engine.
//! It is NOT intended to replace industry-standard ciphers for external
//! communication or to provide production-grade security guarantees.
//!
//! Security properties (intended, not formally proven):
//! - Key size: 32 bytes (256 bits), derived from SHA-256 or a password.
//! - Nonce/IV: 16 bytes random (must be unique per message; never reused
//!   with the same key). The nonce is transmitted in the clear alongside
//!   the ciphertext in the [EverbloomSecurity_Stream] framing format.
//! - Internal state: 128-bit block split into 4 x 32-bit words; 4 Feistel
//!   rounds with custom ARX mixing and a user-defined 8-bit S-box.
//! - The stream is produced by XORing ciphertext bytes with the keystream
//!   generated by feeding the internal state through the round function
//!   repeatedly (counter mode derived from the internal state).
//! - Integrity is NOT provided by the cipher itself; callers must layer
//!   HMAC-SHA256 on top (see `compute_tag` / `verify_tag`).
//!
//! The cipher is exposed as a `Cipher` trait compatible with the engine's
//! existing encoder/decoder pipeline (`engine/src/ndjson.rs`,
//! `sandbox_monitor/src/lib.rs`, etc.).

use sha2::{Digest, Sha256};
use getrandom::getrandom;

/// Key derivation function (KDF) based on a custom iterative hash chain.
/// Derives a 32-byte key from an arbitrary-length seed string or bytes.
/// Not intended to be a standard PBKDF2/Argon2 replacement.
pub fn derive_key(seed_bytes: &[u8]) -> [u8; 32] {
    let mut state = [0u8; 32];
    // Initialize with first 32 bytes of SHA-256(seed) or padded seed.
    let mut hasher = Sha256::new();
    hasher.update(seed_bytes);
    let digest = hasher.finalize();
    state.copy_from_slice(&digest[..32]);
    // Custom KDF chain: 4 iterations of ARX-like mixing.
    for i in 0..4 {
        let mix = ((seed_bytes.len() as u64).wrapping_mul(0x9E3779B97F4A7C15) >> (i as u64)) as u8;
        for j in 0..32 {
            state[j] = state[j].wrapping_add(mix).rotate_left(i as u32 + 1);
        }
        // Re-seed each round with the previous state.
        let mut hasher2 = Sha256::new();
        hasher2.update(&state);
        hasher2.update(&[i as u8; 1]);
        let digest2 = hasher2.finalize();
        state.copy_from_slice(&digest2[..32]);
    }
    state
}

