/// Invert the S-box (used during decryption).
pub const CUSTOM_SBOX_INV: [u8; 256] = {
    let mut inv = [0u8; 256];
    let mut i = 0usize;
    while i < 256 {
        inv[CUSTOM_SBOX[i] as usize] = i as u8;
        i += 1;
    }
    inv
};

/// Custom Feistel round function (4-word state -> 4-word output).
/// Each round applies ARX mixing on the left half and feeds the result
/// through the S-box into the right half's XOR.
fn feistel_round(words: [u32; 4], round_index: usize) -> [u32; 4] {
    let [l0, l1, l2, l3] = words;
    // Custom ARX mix: rotate-left by (1 + (index % 7)), XOR with a constant,
    // add with a derived round constant based on the index.
    let rc = 0xA5C3E7F1_u32.wrapping_add(round_index as u32);
    let mix0 = l0.rotate_left(1 + ((0 + round_index) % 7) as u32);
    let left_after_mix = mix0 ^ rc;
    let s_val = CUSTOM_SBOX[(left_after_mix >> 24) as usize & 0xFF] as u32;
    let right_after_sbox = (l1 ^ (s_val << 8)).rotate_left(3);
    let mix1 = l2.rotate_left(2 + ((2 + round_index) % 7) as u32);
    let mix2 = l3.rotate_left(3 + ((3 + round_index) % 7) as u32);
    [left_after_mix, right_after_sbox, mix1, mix2]
}

/// The cipher state structure: holds key-derived words and the nonce.
pub struct EverbloomCipher {
    /// 32-byte derived key.
    pub key_words: [u32; 4],
    /// 16-byte nonce (unique per message; never reused with same key).
    pub nonce: [u8; 16],
}

impl EverbloomCipher {
    /// Initialize the cipher with a seed bytes array. Derives the internal
    /// 128-bit key and stores the nonce (must be set externally before
    /// encryption; never reuse the same nonce+key pair).
    pub fn new_from_seed(seed_bytes: &[u8]) -> Self {
        let k = derive_key(seed_bytes);
        let mut nonce = [0u8; 16];
        // Derive the nonce deterministically from the seed as well (in
        // production, the caller should supply a random nonce).
        let mut hasher = Sha256::new();
        hasher.update(&k);
        hasher.update(b"EVERBLOOM_NONCE_DERIVE_V1");
        let digest = hasher.finalize();
        nonce.copy_from_slice(&digest[..16]);
        Self {
            key_words: [
                u32::from_le_bytes([k[0], k[1], k[2], k[3]]),
                u32::from_le_bytes([k[4], k[5], k[6], k[7]]),
                u32::from_le_bytes([k[8], k[9], k[10], k[11]]),
                u32::from_le_bytes([k[12], k[13], k[14], k[15]]),
            ],
            nonce,
        }
    }

    /// Set a user-supplied nonce (must be unique per message for security).
    pub fn set_nonce(&mut self, nonce_bytes: &[u8; 16]) {
        self.nonce = *nonce_bytes;
    }

    /// Produce the keystream block for the current internal counter.
    /// The counter is derived from the nonce + a message index word.
    fn keystream_block(&self, index: u32) -> [u8; 16] {
        // Initialize counter = nonce || index (little-endian for index).
        let mut block = [0u8; 16];
        block[..16].copy_from_slice(&self.nonce);
        block[12..16].copy_from_slice(&index.to_le_bytes());
        // Derive a 16-byte output by feeding the counter through the Feistel
        // rounds 4 times and collecting the 4-word outputs as bytes.
        let mut state_words = [
            u32::from_le_bytes([block[0], block[1], block[2], block[3]]),
            u32::from_le_bytes([block[4], block[5], block[6], block[7]]),
            u32::from_le_bytes([block[8], block[9], block[10], block[11]]),
            u32::from_le_bytes([block[12], block[13], block[14], block[15]]),
        ];
        for r in 0..4 {
            state_words = feistel_round(state_words, r);
        }
        // Mix the key words into the output for diffusion.
        for r in 0..4 {
            state_words[r] = state_words[r].wrapping_add(self.key_words[r]);
        }
        // Convert back to bytes.
        let mut out_bytes = [0u8; 16];
        out_bytes[..4].copy_from_slice(&state_words[0].to_le_bytes());
        out_bytes[4..8].copy_from_slice(&state_words[1].to_le_bytes());
        out_bytes[8..12].copy_from_slice(&state_words[2].to_le_bytes());
        out_bytes[12..16].copy_from_slice(&state_words[3].to_le_bytes());
        out_bytes
    }

    /// Encrypt (or decrypt) a byte buffer by XORing with the keystream.
    /// The same function works for both directions.
    pub fn apply_keystream(&self, data: &mut [u8]) {
        for (chunk_index, chunk) in data.chunks_mut(16).enumerate() {
            let stream_block = self.keystream_block(chunk_index as u32);
            for (byte_index, byte_ref) in chunk.iter_mut().enumerate() {
                *byte_ref ^= stream_block[byte_index];
            }
        }
    }

    /// Compute an HMAC-SHA256 integrity tag over the ciphertext (after
    /// applying the keystream). This tag is separate from the cipher and
    /// should be transmitted/appended to the ciphertext for verification.
    pub fn compute_tag(&self, ciphertext: &[u8]) -> [u8; 32] {
        let mut mac_input = Vec::with_capacity(4 * 4 + self.nonce.len() + ciphertext.len());
        mac_input.extend_from_slice(&self.key_words[0].to_le_bytes());
        mac_input.extend_from_slice(&self.key_words[1].to_le_bytes());
        mac_input.extend_from_slice(&self.key_words[2].to_le_bytes());
        mac_input.extend_from_slice(&self.key_words[3].to_le_bytes());
        mac_input.extend_from_slice(&self.nonce);
        mac_input.extend_from_slice(ciphertext);
        hmac_sha256(b"EVERBLOOM_STREAM_TAG_V1", &mac_input)
    }
}

/// High-level encryption of a message string or byte buffer.
/// Produces a [EverbloomSecurity_Stream] framing format:
///
///   [4 bytes: magic "HEAV"]
///   [2 bytes: version (little-endian, value 1)]
///   [2 bytes: nonce length (always 16 for current version)]
///   [16 bytes: nonce]
///   [4 bytes: ciphertext length (little-endian)]
///   [N bytes: ciphertext (keystream XOR'd plaintext)]
///   [32 bytes: HMAC tag (SHA-256 over nonce || ciphertext)]
///
/// This allows the receiver to extract the nonce and verify the tag
/// before decrypting. The format is intentionally self-describing.
pub fn encrypt_payload(plaintext: &[u8], key_bytes: &[u8]) -> Vec<u8> {
    let nonce_bytes = generate_nonce();
    let mut cipher = EverbloomCipher::new_from_seed(key_bytes);
    cipher.set_nonce(&nonce_bytes);
    let mut ciphertext = plaintext.to_vec();
    cipher.apply_keystream(&mut ciphertext);
    let tag = cipher.compute_tag(&ciphertext);
    let mut out = Vec::with_capacity(4 + 2 + 2 + 16 + 4 + ciphertext.len() + 32);
    out.extend_from_slice(b"HEAV");
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&(16u16).to_le_bytes());
    out.extend_from_slice(&nonce_bytes);
    out.extend_from_slice(&(ciphertext.len() as u32).to_le_bytes());
    out.extend_from_slice(&ciphertext);
    out.extend_from_slice(&tag);
    out
}

/// Decrypt a payload produced by `encrypt_payload`. Returns None if the
/// framing is invalid, the tag doesn't match, or any parsing error occurs.
pub fn decrypt_payload(payload_bytes: &[u8], key_bytes: &[u8]) -> Option<Vec<u8>> {
    if payload_bytes.len() < 4 + 2 + 2 + 16 + 4 + 32 {
        return None;
    }
    if &payload_bytes[0..4] != b"HEAV" {
        return None;
    }
    let version = u16::from_le_bytes([payload_bytes[4], payload_bytes[5]]);
    if version != 1 {
        return None;
    }
    let nonce_len = u16::from_le_bytes([payload_bytes[6], payload_bytes[7]]) as usize;
    if nonce_len != 16 {
        return None;
    }
    let nonce_start = 8;
    let nonce_bytes_array: [u8; 16] = payload_bytes[nonce_start..nonce_start + 16].try_into().ok()?;
    let ciphertext_len_start = nonce_start + nonce_len;
    let ciphertext_len = u32::from_le_bytes([
        payload_bytes[ciphertext_len_start],
        payload_bytes[ciphertext_len_start + 1],
        payload_bytes[ciphertext_len_start + 2],
        payload_bytes[ciphertext_len_start + 3],
    ]) as usize;
    let ciphertext_start = ciphertext_len_start + 4;
    let ciphertext_end = ciphertext_start + ciphertext_len;
    let ciphertext_slice = payload_bytes.get(ciphertext_start..ciphertext_end)?;
    let tag_start = ciphertext_end;
    let expected_tag_slice = payload_bytes.get(tag_start..tag_start + 32)?;
    if payload_bytes.len() < tag_start + 32 {
        return None;
    }
    let mut cipher = EverbloomCipher::new_from_seed(key_bytes);
    cipher.set_nonce(&nonce_bytes_array);
    let computed_tag = cipher.compute_tag(ciphertext_slice);
    if computed_tag.as_slice() != expected_tag_slice {
        return None;
    }
    let mut plaintext = ciphertext_slice.to_vec();
    cipher.apply_keystream(&mut plaintext);
    Some(plaintext)
}

/// Compute a simple HMAC-SHA256 over arbitrary data (helper for callers
/// who want an additional integrity layer on top of the stream cipher).
pub fn compute_tag_custom(key_bytes: &[u8], message_bytes: &[u8]) -> [u8; 32] {
    hmac_sha256(key_bytes, message_bytes)
}

/// Verify a custom HMAC-SHA256 tag over arbitrary data.
pub fn verify_tag_custom(key_bytes: &[u8], message_bytes: &[u8], expected_tag_bytes: &[u8]) -> bool {
    if expected_tag_bytes.len() != 32 {
        return false;
    }
    let computed = hmac_sha256(key_bytes, message_bytes);
    computed.as_slice() == expected_tag_bytes
}

/// Generate a cryptographically secure random 16-byte nonce.
/// Uses getrandom (which wraps BCryptGenRandom on Windows, /dev/urandom on Unix).
pub fn generate_nonce() -> [u8; 16] {
    let mut out = [0u8; 16];
    getrandom(&mut out).expect("CSPRNG failure: unable to generate nonce");
    out
}

/// Proper HMAC-SHA256 implementation (RFC 2104).
/// This replaces the previous plain SHA-256 "tag" with a real MAC.
fn hmac_sha256(key: &[u8], message: &[u8]) -> [u8; 32] {
    const BLOCK_SIZE: usize = 64;
    let mut key_padded = [0u8; BLOCK_SIZE];
    if key.len() <= BLOCK_SIZE {
        key_padded[..key.len()].copy_from_slice(key);
    } else {
        let hash = Sha256::digest(key);
        key_padded[..hash.len()].copy_from_slice(&hash);
    }
    let mut ipad = key_padded;
    let mut opad = key_padded;
    for byte in ipad.iter_mut() {
        *byte ^= 0x36;
    }
    for byte in opad.iter_mut() {
        *byte ^= 0x5c;
    }
    let mut inner = Sha256::new();
    inner.update(&ipad);
    inner.update(message);
    let inner_hash = inner.finalize();
    let mut outer = Sha256::new();
    outer.update(&opad);
    outer.update(&inner_hash);
    let mut result = [0u8; 32];
    result.copy_from_slice(&outer.finalize());
    result
}

#[cfg(test)]
mod crypto_tests {
    use super::*;

    #[test]
    fn custom_cipher_roundtrip_works() {
        let key = b"EverbloomSecurity-test-key-v1-seed-string-for-cipher";
        let msg = b"HELIO_TEST_MESSAGE_FOR_CUSTOM_CIPHER_20260829";
        let ciphertext = encrypt_payload(msg, key);
        assert!(ciphertext.starts_with(b"HEAV"));
        let plaintext = decrypt_payload(&ciphertext, key);
        assert!(plaintext.is_some());
        assert_eq!(plaintext.unwrap().as_slice(), msg.as_slice());
    }

    #[test]
    fn custom_cipher_tag_verifies() {
        let key = b"test-key-for-tag-verification-only";
        let msg = b"test message";
        let ciphertext = encrypt_payload(msg, key);
        assert!(ciphertext.len() > msg.len() + 4);
    }

    #[test]
    fn nonce_is_random_each_call() {
        let n1 = generate_nonce();
        let n2 = generate_nonce();
        assert_ne!(n1, n2, "nonces must be unique across calls");
    }

    #[test]
    fn hmac_sha256_matches_reference() {
        let key = b"secret-key";
        let msg = b"message-to-authenticate";
        let tag = hmac_sha256(key, msg);
        assert_eq!(tag.len(), 32);
        assert_ne!(tag, [0u8; 32], "HMAC must not be all zeros");
    }

    #[test]
    fn encrypt_decrypt_roundtrip_with_random_nonce() {
        let key = b"roundtrip-test-key";
        let messages: Vec<&[u8]> = vec![
            b"short",
            b"exactly16chars!!",
            b"a longer message that spans multiple blocks for testing",
            b"",
        ];
        for msg in messages {
            let ct = encrypt_payload(msg, key);
            let pt = decrypt_payload(&ct, key).expect("decrypt failed");
            assert_eq!(pt, msg, "roundtrip mismatch for length {}", msg.len());
        }
    }

    #[test]
    fn tampered_ciphertext_fails_decryption() {
        let key = b"tamper-test-key";
        let msg = b"original message";
        let mut ct = encrypt_payload(msg, key);
        if ct.len() > 50 {
            ct[50] ^= 0xFF;
        }
        assert!(decrypt_payload(&ct, key).is_none(), "tampered ciphertext must fail");
    }

    #[test]
    fn wrong_key_fails_decryption() {
        let key1 = b"correct-key";
        let key2 = b"wrong-key!!";
        let msg = b"secret data";
        let ct = encrypt_payload(msg, key1);
        assert!(decrypt_payload(&ct, key2).is_none(), "wrong key must fail");
    }
}
